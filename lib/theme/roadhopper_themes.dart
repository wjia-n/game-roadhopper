/// Hopper character styles — the frog the player drives across the road.
/// First 4 are FREE; the rest (and the custom creator) are PRO.
class HopperStyleDef {
  final int id;
  final String name;
  final Color body;
  final Color belly;
  final Color? spots; // null = no spots
  final String pattern; // 'spots' | 'stripes' | 'plain' | 'metal' | 'mask'
  final bool pro;

  const HopperStyleDef({
    required this.id,
    required this.name,
    required this.body,
    required this.belly,
    this.spots,
    this.pattern = 'spots',
    this.pro = false,
  });
}

